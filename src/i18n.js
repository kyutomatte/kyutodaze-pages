export function getLocalizedValue(row, field, locale = DEFAULT_LOCALE) {
  const isEnglish = locale === "en";
  const primary = row?.[isEnglish ? `${field}_en` : field];
  const fallback = row?.[isEnglish ? field : `${field}_en`];
  return primary || fallback || "";
}

export function createLocaleStore({
  storage = typeof localStorage === "undefined" ? null : localStorage,
  documentElement = typeof document === "undefined" ? null : document.documentElement
} = {}) {
  const storedLocale = storage?.getItem(LOCALE_STORAGE_KEY);
  let locale = SUPPORTED_LOCALES.has(storedLocale) ? storedLocale : DEFAULT_LOCALE;
  const listeners = new Set();

  if (documentElement) documentElement.lang = locale;

  return {
    getLocale: () => locale,
    setLocale(nextLocale) {
      if (!SUPPORTED_LOCALES.has(nextLocale)) return locale;

      locale = nextLocale;
      storage?.setItem(LOCALE_STORAGE_KEY, locale);
      if (documentElement) documentElement.lang = locale;
      listeners.forEach((listener) => listener(locale));
      return locale;
    },
    subscribe(listener) {
      listeners.add(listener);
      return () => listeners.delete(listener);
    }
  };
}

export function translate(key, locale = DEFAULT_LOCALE) {
  return translations[SUPPORTED_LOCALES.has(locale) ? locale : DEFAULT_LOCALE][key] ?? key;
}
